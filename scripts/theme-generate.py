def generate_hypr(c, config):
    text = f"""-- Generated by theme.sh — do not edit by hand.
return {{
    active_border = {{
        colors = {{ "{hypr_color(c['accent'], 'ee')}", "{hypr_color(c['accent_alt'], 'ee')}" }},
        angle = 45,
    }},
    inactive_border = "{hypr_color(c['bg_alt'], 'aa')}",
}}
"""
    write(os.path.join(config, "hypr", "theme.lua"), text)


def generate_kdeglobals(c, p, config):
    path = os.path.join(config, "kdeglobals")
    template = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))),
                            "copied", "kdeglobals")
    source = path if os.path.exists(path) else template
    if not os.path.exists(source):
        return
    with open(source, encoding="utf-8") as fh:
        lines = fh.read().splitlines()

    window = {
        "BackgroundAlternate": kde_rgb(c["bg"]),
        "BackgroundNormal": kde_rgb(c["bg_alt"]),
        "DecorationFocus": kde_rgb(c["accent"]),
        "DecorationHover": kde_rgb(c["accent"]),
        "ForegroundActive": kde_rgb(c["accent"]),
        "ForegroundInactive": kde_rgb(c["muted"]),
        "ForegroundLink": kde_rgb(c["accent"]),
        "ForegroundNegative": kde_rgb(c["danger"]),
        "ForegroundNeutral": kde_rgb(c["warn"]),
        "ForegroundNormal": kde_rgb(c["fg"]),
        "ForegroundPositive": kde_rgb(c["good"]),
        "ForegroundVisited": kde_rgb(c["accent_alt"]),
    }
    view = dict(window, BackgroundAlternate=kde_rgb(c["bg_alt"]),
                BackgroundNormal=kde_rgb(c["bg"]))
    button = dict(window, BackgroundAlternate=kde_rgb(c["bg_hover"]),
                  BackgroundNormal=kde_rgb(c["bg_alt"]))
    selection = dict(window, BackgroundAlternate=kde_rgb(mix(c["accent"], c["bg"], 0.2)),
                     BackgroundNormal=kde_rgb(c["accent"]),
                     ForegroundNormal=kde_rgb(c["on_accent"]),
                     ForegroundActive=kde_rgb(c["on_accent"]),
                     ForegroundInactive=kde_rgb(c["on_accent"]))
    tooltip = dict(window, BackgroundAlternate=kde_rgb(c["bg"]),
                   BackgroundNormal=kde_rgb(c["bg_alt"]))
    header = dict(window, BackgroundAlternate=kde_rgb(c["bg"]),
                  BackgroundNormal=kde_rgb(c["bg_alt"]))
    header_inactive = dict(header, ForegroundNormal=kde_rgb(c["muted"]),
                           ForegroundInactive=kde_rgb(c["muted"]))
    complementary = dict(window, BackgroundAlternate=kde_rgb(c["bg_alt"]),
                         BackgroundNormal=kde_rgb(c["bg"]))
    sections = {
        "[Colors:Window]": window,
        "[Colors:View]": view,
        "[Colors:Button]": button,
        "[Colors:Selection]": selection,
        "[Colors:Tooltip]": tooltip,
        "[Colors:Header]": header,
        "[Colors:Header][Inactive]": header_inactive,
        "[Colors:Complementary]": complementary,
    }

    section = None
    output = []
    for line in lines:
        if line.startswith("[") and line.endswith("]"):
            section = line
            output.append(line)
            continue
        if "=" in line and section in sections:
            key = line.split("=", 1)[0]
            if key in sections[section]:
                output.append("%s=%s" % (key, sections[section][key]))
                continue
        if line.startswith("activeBackground="):
            output.append("activeBackground=" + kde_rgb(c["bg_alt"]))
        elif line.startswith("activeBlend="):
            output.append("activeBlend=" + kde_rgb(c["fg"]))
        elif line.startswith("activeForeground="):
            output.append("activeForeground=" + kde_rgb(c["fg"]))
        elif line.startswith("inactiveBackground="):
            output.append("inactiveBackground=" + kde_rgb(c["bg"]))
        elif line.startswith("inactiveBlend="):
            output.append("inactiveBlend=" + kde_rgb(c["muted"]))
        elif line.startswith("inactiveForeground="):
            output.append("inactiveForeground=" + kde_rgb(c["muted"]))
        elif line.startswith("ColorSchemeHash="):
            digest = hashlib.md5(("".join("%s=%s" % item for item in sorted(p.items()))).encode()).hexdigest()
            output.append("ColorSchemeHash=" + digest)
        elif line.startswith("LookAndFeelPackage="):
            mode = p.get("MODE", "dark").lower()
            output.append("LookAndFeelPackage=org.kde.%s.desktop" %
                          ("breezedark" if mode == "dark" else "breeze"))
        else:
            output.append(line)

    write(path, "\n".join(output) + "\n")


def main():
    if len(sys.argv) < 2:
        print("usage: theme-generate.py <theme-dir> [config-dir]", file=sys.stderr)
        return 2
    theme_dir = os.path.abspath(sys.argv[1])
    config = os.path.abspath(sys.argv[2]) if len(sys.argv) > 2 else os.path.expanduser("~/.config")
    palette_path = os.path.join(theme_dir, "palette.env")
    if not os.path.exists(palette_path):
        print("missing palette.env in " + theme_dir, file=sys.stderr)
        return 1
    p = parse_env(palette_path)
    required = ["BG", "BG_ALT", "BG_HOVER", "FG", "FG_MUTED", "ACCENT",
                "ACCENT_ALT", "WARN", "GOOD", "DANGER"]
    missing = [key for key in required if key not in p]
    if missing:
        print("palette.env is missing: " + ", ".join(missing), file=sys.stderr)
        return 1
    c = build_colors(p)
    generate_swaync(c, config)
    generate_ghostty(c, p, config)
    generate_gtk(c, config)
    generate_hypr(c, config)
    generate_kdeglobals(c, p, config)
    print("theme files generated for " + os.path.basename(theme_dir))
    return 0


if __name__ == "__main__":
    sys.exit(main())
