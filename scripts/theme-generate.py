#!/usr/bin/env python3
"""Generate per-app theme files from themes/<name>/palette.env.

Usage: theme-generate.py <theme-dir> [config-dir]

Writes (inside config-dir, default ~/.config):
  swaync/theme.css          colours imported by swaync/style.css
  ghostty/theme             Ghostty colours (loaded with config-file = theme)
  gtk-3.0/colors.css        Breeze GTK colour variables (GTK3 apps)
  gtk-4.0/colors.css        Breeze GTK colour variables (GTK4 apps)
  hypr/theme.lua            Hyprland border colours (loaded by appearance.lua)
  kdeglobals                KDE/Qt colour scheme (Dolphin, Qt apps, ...)
"""

import hashlib
import os
import sys


def parse_env(path):
    data = {}
    with open(path, encoding="utf-8") as fh:
        for line in fh:
            line = line.strip()
            if not line or line.startswith("#") or "=" not in line:
                continue
            key, value = line.split("=", 1)
            data[key.strip()] = value.strip().strip('"').strip("'")
    return data


def rgb(value):
    value = value.lstrip("#")
    if len(value) == 3:
        value = "".join(ch * 2 for ch in value)
    return tuple(int(value[i:i + 2], 16) for i in (0, 2, 4))


def hx(value):
    return "#%02x%02x%02x" % value


def mix(first, second, amount):
    """Mix two hex colours. amount=0 -> first, amount=1 -> second."""
    a, b = rgb(first), rgb(second)
    return hx(tuple(round(a[i] + (b[i] - a[i]) * amount) for i in range(3)))


def rgba(value, alpha):
    r, g, b = rgb(value)
    return "rgba(%d, %d, %d, %s)" % (r, g, b, alpha)


def hypr_color(value, alpha):
    return "rgba(%s%s)" % (value.lstrip("#").lower(), alpha)


def luminance(value):
    r, g, b = (c / 255.0 for c in rgb(value))
    return 0.2126 * r + 0.7152 * g + 0.0722 * b


def readable_on(value):
    return "#000000" if luminance(value) > 0.55 else "#ffffff"


def kde_rgb(value):
    return "%d,%d,%d" % rgb(value)


def write(path, text):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8") as fh:
        fh.write(text)


def build_colors(p):
    bg = p["BG"]
    bg_alt = p["BG_ALT"]
    bg_hover = p["BG_HOVER"]
    fg = p["FG"]
    muted = p["FG_MUTED"]
    accent = p["ACCENT"]
    accent_alt = p["ACCENT_ALT"]
    warn = p["WARN"]
    good = p["GOOD"]
    danger = p["DANGER"]
    on_accent = readable_on(accent)
    border = mix(bg, fg, 0.22)
    return {
        "bg": bg,
        "bg_alt": bg_alt,
        "bg_hover": bg_hover,
        "fg": fg,
        "muted": muted,
        "accent": accent,
        "accent_alt": accent_alt,
        "on_accent": on_accent,
        "warn": warn,
        "good": good,
        "danger": danger,
        "border": border,
        "soft_accent": mix(bg, accent, 0.35),
        "soft_warn": mix(bg, warn, 0.35),
        "soft_good": mix(bg, good, 0.35),
        "soft_danger": mix(bg, danger, 0.35),
        "soft_fg": mix(bg, fg, 0.35),
        "soft_muted": mix(bg, muted, 0.55),
    }


def generate_swaync(c, config):
    text = f"""/* Generated by theme.sh — do not edit by hand. */
@define-color bg-main {rgba(c['bg'], '0.96')};
@define-color bg-card {rgba(c['bg_alt'], '0.92')};
@define-color bg-hover {rgba(c['bg_hover'], '0.95')};
@define-color border-subtle {rgba(c['accent'], '0.25')};
@define-color accent #{c['accent']};
@define-color danger #{c['danger']};
@define-color text-main #{c['fg']};
@define-color text-muted #{c['muted']};
"""
    write(os.path.join(config, "swaync", "theme.css"), text)


def generate_ghostty(c, p, config):
    lines = [
        "# Generated by theme.sh — do not edit by hand.",
        f"background = #{c['bg']}",
        f"foreground = #{c['fg']}",
        f"cursor-color = #{c['accent']}",
        f"cursor-text = {c['on_accent']}",
        f"selection-background = #{c['accent']}",
        f"selection-foreground = {c['on_accent']}",
    ]
    for index in range(16):
        value = p.get("ANSI%d" % index, c["fg"])
        lines.append(f"palette = {index}=#{value}")
    write(os.path.join(config, "ghostty", "theme"), "\n".join(lines) + "\n")


